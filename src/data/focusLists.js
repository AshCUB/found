// Helper function to get moon phase for a given date
export function getMoonPhaseForDate(date) {
  // Calculate moon phase (0-7, where 0 = new moon, 4 = full moon)
  // This is a simplified calculation
  const knownNewMoon = new Date('2024-01-11'); // Known new moon date
  const lunarCycle = 29.53; // Days in a lunar cycle
  const daysSinceKnown = (date - knownNewMoon) / (1000 * 60 * 60 * 24);
  const phase = Math.floor((daysSinceKnown % lunarCycle) / (lunarCycle / 8)) % 8;
  return phase;
}

// Helper function to get moon phase item for a given date
export function getMoonPhaseItem(date) {
  const phaseIndex = getMoonPhaseForDate(date);
  const moonList = focusLists.find(list => list.id === 'moon-phases');
  return moonList ? moonList.items[phaseIndex] : null;
}
